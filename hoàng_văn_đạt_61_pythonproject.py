import pandas as pd

# Yêu cầu 1: Tạo DataFrame
data = {
    'Ho_ten': [
        'Nguyễn Văn A', 'Trần Thị B', 'Lê Văn C',
        'Phạm Thị D', 'Hoàng Văn E', 'Vũ Thị F',
        'Đỗ Văn G', 'Bùi Thị H', 'Ngô Văn I', 'Dương Thị K'
    ],
    'Chuyen_can': [8.0, 9.0, 10.0, 7.0, 6.5, 8.0, 9.0, 5.0, 7.5, 9.5],
    'Giua_ky': [7.5, 8.0, 9.0, 6.0, 5.0, 7.0, 8.5, 4.5, 6.5, 9.0],
    'Cuoi_ky': [8.0, 8.5, 9.5, 6.5, 5.5, 7.5, 9.0, 4.0, 7.0, 9.5]
}

df = pd.DataFrame(data)

# Yêu cầu 2: Tính điểm tổng kết
df['Tong_ket'] = (
    0.2 * df['Chuyen_can']
    + 0.3 * df['Giua_ky']
    + 0.5 * df['Cuoi_ky']
).round(2)

# Yêu cầu 3: Thống kê
def xep_loai(diem):
    if diem >= 8.5:
        return 'Giỏi'
    elif diem >= 7.0:
        return 'Khá'
    elif diem >= 5.0:
        return 'Trung bình'
    else:
        return 'Yếu'

df['Xep_loai'] = df['Tong_ket'].apply(xep_loai)

# Hiển thị bảng kết quả
print("BẢNG ĐIỂM VÀ XẾP LOẠI SINH VIÊN")
print(df.to_string(index=False))
# 1. Tính điểm tổng kết trung bình của lớp
diem_trung_binh = df['Tong_ket'].mean()
print("\nĐiểm tổng kết trung bình của lớp:", round(diem_trung_binh, 2))

# 2. Tìm sinh viên có điểm tổng kết cao nhất
sinh_vien_cao_nhat = df.loc[df['Tong_ket'].idxmax()]
print("sinh viên có diểm tổng kết cao nhất:")
print("Họ tên:", sinh_vien_cao_nhat['Ho_ten'])
print("Điểm tổng kết:", sinh_vien_cao_nhat['Tong_ket'])
# 3. Tìm sinh viên có điểm tổng kết thấp nhất
sinh_vien_thap_nhat = df.loc[df['Tong_ket'].idxmin()]
print("sinh viên có điểm tổng kết thấp nhất:")
print("Họ tên:", sinh_vien_thap_nhat['Ho_ten'])
print("Điểm tổng kết:", sinh_vien_thap_nhat['Tong_ket'])

# 4. Đếm số sinh viên đạt (điểm tổng kết >= 5)
so_sinh_vien_dat = (df['Tong_ket'] >= 5).sum()
print("\nSố sinh viên đạt:", so_sinh_vien_dat)
import matplotlib.pyplot as plt

plt.bar(df["Ho_ten"], df["Tong_ket"], color="skyblue")

plt.title("Điểm tổng kết của 10 sinh viên")
plt.xlabel("Tên sinh viên")
plt.ylabel("Điểm tổng kết")
plt.ylim(0, 10)
plt.xticks(rotation=45)
plt.tight_layout()
plt.show()